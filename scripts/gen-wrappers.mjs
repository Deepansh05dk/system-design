// Generates Astro wrappers for every React island so MDX lessons can use
// interactive components without importing them or adding client directives.
import { readdirSync, writeFileSync, mkdirSync } from 'node:fs';

const islandsDir = 'src/components/islands';
const outDir = 'src/components/mdx';
const skip = new Set(['Widget', 'MarkComplete']);
mkdirSync(outDir, { recursive: true });

const names = readdirSync(islandsDir)
  .filter((f) => f.endsWith('.tsx'))
  .map((f) => f.replace(/\.tsx$/, ''))
  .filter((n) => !skip.has(n))
  .sort();

for (const n of names) {
  writeFileSync(
    `${outDir}/${n}.astro`,
    `---\nimport C from '../islands/${n}';\n---\n\n<C client:visible {...Astro.props} />\n`,
  );
}

const statics = ['Callout', 'Versus', 'Takeaways', 'Term'];
const lines = [
  '// Generated by scripts/gen-wrappers.mjs — do not edit by hand.',
  ...statics.map((s) => `import ${s} from '../${s}.astro';`),
  ...names.map((n) => `import ${n} from './${n}.astro';`),
  '',
  `export const mdxComponents = { ${[...statics, ...names].join(', ')} };`,
  '',
];
writeFileSync(`${outDir}/index.ts`, lines.join('\n'));
console.log(`Generated ${names.length} island wrappers.`);
